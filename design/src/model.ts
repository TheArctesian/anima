// The resolved token as the output formats see it. Pure data: no Style Dictionary types.

import type { SpringShape } from './spring.ts';

export type Fields = Readonly<Record<string, unknown>>;

/** A token's value in another mode: as written, aliases intact, and with every alias resolved. */
export interface ModeValue {
  readonly source: unknown;
  readonly value: unknown;
}

export interface Token {
  /** The K5 name, for example `status-up` or `spring-default`. */
  readonly name: string;
  /** The full source path, for example `motion.spring.default`; names the token in errors. */
  readonly path: string;
  /** Source path without the last segment, for example `motion.spring`. Groups the reference page. */
  readonly group: string;
  /** DTCG `$type`, or a custom type such as `spring`. */
  readonly type: string;
  /** The value with every alias resolved. */
  readonly value: unknown;
  /** The value as written in the source, aliases intact. */
  readonly source: unknown;
  /** The use of the token (`$description`). */
  readonly description: string;
  /** The value under `prefers-reduced-motion: reduce`, when it differs (D-5). */
  readonly reduced: unknown;
  /** The value in the light theme, when it differs (UI-005); only a semantic colour has one (TOK-011). */
  readonly light: ModeValue | undefined;
  /** The palette a semantic role belongs to (`graphite`, `nord`); undefined for primitives and shared tokens (UI-023). */
  readonly palette: string | undefined;
}

/** A registered palette (UI-023): its name, licence line, whether it is the default, and its source file. */
export interface Palette {
  readonly id: string;
  readonly name: string;
  readonly licence: string;
  readonly default: boolean;
  readonly file: string;
}

export const GENERATED_NOTICE = 'generated by design/src — do not edit (TOK-001)';

/** A palette role lives at `color.role.<palette>.<role>`; everything else is named by its path. */
function isRolePath(path: readonly string[]): boolean {
  return path[1] === 'role' && path.length >= 4;
}

/** The palette of a semantic role path, or undefined for any other path (UI-023). */
export function paletteOfPath(path: readonly string[]): string | undefined {
  return isRolePath(path) ? path[2] : undefined;
}

/** Terminal palette tokens feed the Rust output only (RA-010); they are not K5 interface names. */
export function isTerminal(token: Token): boolean {
  return token.group === 'terminal' || token.group.startsWith('terminal.');
}

/** A semantic colour (a palette role, or a shared colour such as `shadow`): the only kind of token a theme may change (TOK-011). */
export function isSemanticColour(token: Token): boolean {
  const semantic = token.group === 'color' || token.group.startsWith('color.role.');
  return semantic && (token.type === 'color' || token.type === 'tint');
}

/**
 * The K5 name of a token: the source path without its first segment, joined by dashes. A palette role is named by its
 * role alone, so `color.role.nord.surface-raised` is `surface-raised` (UI-023).
 */
export function tokenName(path: readonly string[]): string {
  return isRolePath(path) ? path.slice(3).join('-') : path.slice(1).join('-');
}

/** The K5 name an alias such as `{color.nord.8}` points at, or undefined for a plain value. */
export function aliasName(source: unknown): string | undefined {
  if (typeof source !== 'string') return undefined;
  const match = /^\{([^{}]+)\}$/.exec(source);
  return match?.[1] ? tokenName(match[1].split('.')) : undefined;
}

/** `var(--name)` for an alias, or the plain string. */
export function aliasOrValue(source: unknown, resolved: unknown): string {
  const name = aliasName(source);
  return name ? `var(--${name})` : String(resolved);
}

export function fieldsOf(value: unknown): Fields {
  if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
    return value as Fields;
  }
  throw new TypeError(`expected an object token value, got ${JSON.stringify(value)}`);
}

export function numberOf(value: unknown): number {
  if (typeof value === 'number') return value;
  if (typeof value === 'string' && value.trim() !== '' && !Number.isNaN(Number(value))) {
    return Number(value);
  }
  throw new TypeError(`expected a number, got ${JSON.stringify(value)}`);
}

/** The number in a value such as `100ms` or `10px`. */
export function leadingNumber(value: unknown): number {
  const match = /^(-?\d+(?:\.\d+)?)/.exec(String(value));
  if (!match?.[1]) throw new TypeError(`no number in ${JSON.stringify(value)}`);
  return Number(match[1]);
}

/** Round to `digits` decimals and drop trailing zeros, so output is stable text. */
export function trimmedDecimal(value: number, digits = 6): string {
  return String(Number(value.toFixed(digits)));
}

export function tokensOfType(tokens: readonly Token[], type: string): Token[] {
  return tokens.filter((token) => token.type === type);
}

/** A token source that cannot be turned into output: names the token and what is wrong with it. */
export class TokenSourceError extends Error {
  constructor(
    readonly tokenPath: string,
    readonly problem: string,
  ) {
    super(`${tokenPath}: ${problem}`);
    this.name = 'TokenSourceError';
  }
}

function isFiniteNumber(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value);
}

/** A spring needs a damping ratio and a positive response time (D-4). */
export function springOf(token: Token): SpringShape {
  const fields: Fields = typeof token.value === 'object' && token.value !== null ? (token.value as Fields) : {};
  const { dampingRatio, responseS } = fields;
  if (!isFiniteNumber(dampingRatio) || !isFiniteNumber(responseS) || responseS <= 0) {
    throw new TokenSourceError(token.path, 'a spring needs numeric dampingRatio and positive responseS');
  }
  return { dampingRatio, responseS };
}

/** A cubic-bezier is four finite numbers. */
export function bezierOf(token: Token): readonly number[] {
  const { value } = token;
  if (!Array.isArray(value) || value.length !== 4 || !value.every(isFiniteNumber)) {
    throw new TokenSourceError(token.path, 'a cubic-bezier needs four finite numbers');
  }
  return value;
}

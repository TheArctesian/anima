/**
 * Writes `apps/client/src/lib/icons/shapes.ts`: the SVG shapes of every Carbon and Simple Icons icon the client names
 * (UI-014, UI-016). The client names an icon by its Iconify id in quotes, for example 'carbon:chip'; this script finds
 * each one in `apps/client/src` and copies its shapes from the pinned icon sets, so the package holds only icons in use.
 *
 *   bun bin/icons.ts <carbon icons.json> <simple-icons icons.json>
 *
 * The two files are `icons.json` from the npm packages named in SOURCES, at those exact versions.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const SOURCES = {
  carbon: { package: '@iconify-json/carbon@1.2.29', licence: 'Apache-2.0, IBM' },
  'simple-icons': { package: '@iconify-json/simple-icons@1.2.101', licence: 'CC0-1.0, Simple Icons Collaborators' },
} as const;

type Prefix = keyof typeof SOURCES;

interface IconSet {
  readonly width?: number;
  readonly height?: number;
  readonly icons: Readonly<Record<string, { readonly body: string; readonly width?: number; readonly height?: number }>>;
  readonly aliases?: Readonly<Record<string, { readonly parent: string }>>;
}

const repository = join(import.meta.dir, '..', '..');
const clientSource = join(repository, 'apps', 'client', 'src');
const target = join(clientSource, 'lib', 'icons', 'shapes.ts');
const ICON_ID = /['"`](carbon|simple-icons):([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g;

function sourceFiles(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return sourceFiles(path);
    return /\.(ts|svelte)$/.test(entry.name) && path !== target ? [path] : [];
  });
}

function namedIcons(): string[] {
  const ids = new Set<string>();
  for (const file of sourceFiles(clientSource)) {
    for (const match of readFileSync(file, 'utf8').matchAll(ICON_ID)) ids.add(`${match[1]}:${match[2]}`);
  }
  return [...ids].sort();
}

/** One self-closing SVG element of an icon body, as its tag and attributes; `fill="currentColor"` is left to the svg. */
function parts(id: string, body: string): [string, Record<string, string>][] {
  const elements = [...body.matchAll(/<([a-z]+)((?:\s+[a-z-]+="[^"]*")*)\s*\/>/g)];
  if (elements.map((element) => element[0]).join('') !== body) throw new Error(`${id}: body is not a list of self-closing elements`);
  return elements.map(([, tag = '', attributes = '']) => {
    const pairs = [...attributes.matchAll(/([a-z-]+)="([^"]*)"/g)].map(([, name = '', value = '']) => [name, value] as const);
    return [tag, Object.fromEntries(pairs.filter(([name, value]) => !(name === 'fill' && value === 'currentColor')))];
  });
}

function shape(sets: Record<Prefix, IconSet>, id: string) {
  const [prefix, name] = id.split(':') as [Prefix, string];
  const set = sets[prefix];
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent ?? ''];
  if (icon === undefined) throw new Error(`${id} is not in ${SOURCES[prefix].package}`);
  return { width: icon.width ?? set.width ?? 16, height: icon.height ?? set.height ?? 16, parts: parts(id, icon.body) };
}

const [carbonPath, simplePath] = process.argv.slice(2);
if (carbonPath === undefined || simplePath === undefined) {
  console.error('usage: bun bin/icons.ts <carbon icons.json> <simple-icons icons.json>');
  process.exit(2);
}
const sets: Record<Prefix, IconSet> = {
  carbon: JSON.parse(readFileSync(carbonPath, 'utf8')) as IconSet,
  'simple-icons': JSON.parse(readFileSync(simplePath, 'utf8')) as IconSet,
};
const ids = namedIcons();
const entries = ids.map((id) => `  '${id}': ${JSON.stringify(shape(sets, id))},`);
const header = [
  `// Generated by design/bin/icons.ts from ${relative(repository, clientSource)}; do not edit (UI-016).`,
  ...Object.values(SOURCES).map((source) => `// ${source.package} (${source.licence})`),
];
writeFileSync(target, `${header.join('\n')}\nexport const ICON_SHAPES = {\n${entries.join('\n')}\n} as const;\n`);
console.log(`${ids.length} icons → ${relative(repository, target)}`);

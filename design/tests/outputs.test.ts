import { beforeAll, describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { buildOutputs, OUTPUT_PATHS } from '../src/outputs.ts';

const root = resolve(import.meta.dir, '..', '..');
let css = '';
let typescript = '';

beforeAll(async () => {
  const outputs = await buildOutputs(root);
  css = outputs[OUTPUT_PATHS.css] ?? '';
  typescript = outputs[OUTPUT_PATHS.typescript] ?? '';
});

/** Names in the K5 table of contracts/tokens.md, ranges such as `nord-0` … `nord-15` expanded. */
function k5Names(): string[] {
  const text = readFileSync(join(root, 'contracts', 'tokens.md'), 'utf8');
  const section = text.slice(text.indexOf('## Names'), text.indexOf('## Rules for consumers'));
  const rows = section.split('\n').filter((line) => line.startsWith('| ') && !line.startsWith('| Group') && !line.startsWith('| ---'));
  return rows.flatMap((row) => {
    const cell = (row.split('|')[2] ?? '').split('(')[0] ?? '';
    const names = [...cell.matchAll(/`([a-z][a-z0-9-]*)`/g)].map((match) => match[1] ?? '');
    const range = /`([a-z]+)-(\d+)` … `[a-z]+-(\d+)`/.exec(cell);
    if (!range) return names;
    const [, prefix = '', first = '0', last = '0'] = range;
    return Array.from({ length: Number(last) - Number(first) + 1 }, (_, index) => `${prefix}-${Number(first) + index}`);
  });
}

const TYPESCRIPT_ONLY = /^(bp-|projection-deceleration$|rubberband-constant$)/;

function declared(name: string): boolean {
  return css.includes(`  --${name}:`) || css.includes(`  --${name}-bg:`);
}

describe('K5 names', () => {
  test('TOK-001 the K5 table parser finds the names at both ends of its ranges', () => {
    const names = k5Names();
    for (const name of ['nord-0', 'nord-15', 'bg', 'spring-momentum', 'threshold-loading-min', 'bp-wide', 'projection-deceleration', 'rubberband-constant']) {
      expect(names).toContain(name);
    }
  });

  test('TOK-001 every K5 name except breakpoints and gesture constants is a custom property in tokens.css', () => {
    const missing = k5Names().filter((name) => !TYPESCRIPT_ONLY.test(name) && !declared(name));
    expect(missing).toEqual([]);
  });

  test('TOK-001 breakpoints are in TypeScript and not in CSS', () => {
    expect(css).not.toContain('--bp-');
    for (const key of ['compact', 'medium', 'wide']) expect(typescript).toContain(`  ${key}: {`);
  });

  test('MOT-032 MOT-033 gesture constants are in tokens.ts with the spec values and absent from tokens.css (R-013)', () => {
    expect(typescript).toContain('export const gesture = {\n  projectionDeceleration: 0.998,\n  rubberbandConstant: 0.55,\n} as const;');
    for (const name of ['projection-deceleration', 'rubberband-constant']) {
      expect(css).not.toContain(name);
      expect(k5Names()).toContain(name);
    }
  });

  test('MOT-032 MOT-033 reduced motion leaves the gesture constants unchanged', () => {
    const reduced = typescript.slice(typescript.indexOf('export const reducedMotion'));
    expect(reduced).not.toContain('gesture');
    expect(reduced).not.toContain('projectionDeceleration');
    expect(reduced).not.toContain('rubberbandConstant');
  });

  test('TOK-001 every generated file starts with the generated header', () => {
    expect(css.startsWith('/* generated by design/src — do not edit (TOK-001) */')).toBe(true);
    expect(typescript.startsWith('// generated by design/src — do not edit (TOK-001)')).toBe(true);
  });
});

describe('colour tokens', () => {
  const SEMANTIC: Record<string, string> = {
    bg: '#2E3440', surface: '#3B4252', 'surface-raised': '#434C5E', border: '#4C566A',
    text: '#ECEFF4', 'text-muted': '#D8DEE9', accent: '#88C0D0', 'accent-alt': '#81A1C1',
    'accent-deep': '#5E81AC', info: '#8FBCBB', 'status-up': '#A3BE8C', 'status-down': '#BF616A',
    'status-degraded': '#EBCB8B', 'status-warning': '#D08770', 'status-maintenance': '#B48EAD',
    'status-unknown': '#4C566A',
  };

  test('UI-001 each semantic colour is a var() of the Nord primitive with its 5.1 hex value', () => {
    for (const [name, hex] of Object.entries(SEMANTIC)) {
      const alias = new RegExp(`  --${name}: var\\(--(nord-\\d+)\\);`).exec(css)?.[1];
      expect(alias).toBeDefined();
      expect(css).toContain(`  --${alias ?? ''}: ${hex};`);
    }
  });

  test('TOK-011 semantic colours alias primitives so a theme changes only semantic tokens (D-8)', () => {
    expect(css).toContain('--accent: var(--nord-8);');
  });

  test('UI-005 a tint is the colour at 12 % over the current surface (D-7)', () => {
    expect(css).toContain('--status-up-tint: color-mix(in srgb, var(--status-up) 12%, var(--surface));');
  });
});

describe('sizes and type', () => {
  test('TOK-020 font sizes and spaces are in rem', () => {
    const sizes = [...css.matchAll(/--(?:text-(?:xs|sm|md|lg|xl|2xl)|space-(?!0:)\d+): ([^;]+);/g)];
    expect(sizes.length).toBe(6 + 10);
    for (const size of sizes) expect(size[1]).toMatch(/^[\d.]+rem$/);
  });

  test('TOK-021 tracking is -0.01em for display, 0 for body and 0.01em for small text', () => {
    expect(css).toContain('--tracking-display: -0.01em;');
    expect(css).toContain('--tracking-body: 0em;');
    expect(css).toContain('--tracking-small: 0.01em;');
  });

  test('UI-010 the interface font is OpenDyslexic Propo with a system fallback; icons fall back to Symbols', () => {
    expect(css).toMatch(/--font-ui: "OpenDyslexic Nerd Font Propo", .*sans-serif;/);
    expect(css).toContain('--font-mono: "OpenDyslexicM Nerd Font Mono", ui-monospace, monospace;');
    expect(css).toContain('--font-icon: "OpenDyslexic Nerd Font Propo", "Symbols Nerd Font";');
  });
});

describe('materials and motion', () => {
  const reducedMotion = (): string => /@media \(prefers-reduced-motion: reduce\) \{[^@]*\n\}/.exec(css)?.[0] ?? '';

  test('MAT-006 chrome is 82 % surface with 20 px blur and 140 % saturation; solid under reduced transparency', () => {
    expect(css).toContain('--material-chrome-bg: color-mix(in srgb, var(--surface) 82%, transparent);');
    expect(css).toContain('--material-chrome-blur: 20px;');
    expect(css).toContain('--material-chrome-saturate: 140%;');
    const transparency = css.slice(css.indexOf('@media (prefers-reduced-transparency: reduce)'));
    expect(transparency).toContain('--material-chrome-bg: var(--surface);');
    expect(transparency).toContain('--material-chrome-blur: 0px;');
  });

  test('MAT-006 increased contrast uses text-muted borders', () => {
    expect(css.slice(css.indexOf('@media (prefers-contrast: more)'))).toContain('--border: var(--text-muted);');
  });

  test('MOT-021 the reduced-motion block changes no threshold', () => {
    expect(reducedMotion()).toContain('--duration-press: 0ms;');
    expect(reducedMotion()).not.toContain('threshold');
  });

  test('MOT-040 under reduced motion every spring becomes an instant move', () => {
    for (const name of ['default', 'snappy', 'move', 'momentum']) {
      expect(reducedMotion()).toContain(`--spring-${name}: 0ms linear;`);
    }
  });

  test('MOT-041 TypeScript exports the reduced values without touching thresholds', () => {
    expect(typescript).toContain('export const reducedMotion = {');
    const reduced = typescript.slice(typescript.indexOf('export const reducedMotion'));
    expect(reduced).not.toContain('threshold');
    expect(reduced).toContain('press: 0,');
  });

  test('MOT-003 the TypeScript spring carries the converted stiffness and damping (K5 form)', () => {
    expect(typescript).toContain('export const spring = {');
    expect(typescript).toMatch(/default: \{\n\s+dampingRatio: 1,\n\s+responseS: 0\.35,\n\s+stiffness: 322\.27\d+,\n\s+damping: 35\.90\d+,/);
  });

  test('MOT-003 CSS springs are a settle time and a linear() curve', () => {
    expect(css).toMatch(/--spring-default: \d+ms linear\(0, [\d., ]+, 1\);/);
  });

  test('5.7.2 eases are cubic-bezier curves', () => {
    expect(css).toContain('--ease-enter: cubic-bezier(0.2, 0, 0, 1);');
    expect(css).toContain('--ease-exit: cubic-bezier(1, 0, 0.8, 1);');
  });
});

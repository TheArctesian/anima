import { beforeAll, describe, expect, test } from 'bun:test';
import { resolve } from 'node:path';
import { buildOutputs, OUTPUT_PATHS } from '../src/outputs.ts';

const root = resolve(import.meta.dir, '..', '..');
let rust = '';
let css = '';
let typescript = '';
let reference = '';

beforeAll(async () => {
  const outputs = await buildOutputs(root);
  rust = outputs[OUTPUT_PATHS.rust] ?? '';
  css = outputs[OUTPUT_PATHS.css] ?? '';
  typescript = outputs[OUTPUT_PATHS.typescript] ?? '';
  reference = outputs[OUTPUT_PATHS.reference] ?? '';
});

const NORD_5_1 = [
  '#2E3440', '#3B4252', '#434C5E', '#4C566A', '#D8DEE9', '#E5E9F0', '#ECEFF4', '#8FBCBB',
  '#88C0D0', '#81A1C1', '#5E81AC', '#BF616A', '#D08770', '#EBCB8B', '#A3BE8C', '#B48EAD',
];

function nordBlock(): string {
  return /pub const NORD: \[Rgb; 16\] = \[\n([^\]]*)\];/.exec(rust)?.[1] ?? '';
}

describe('Rust output', () => {
  test('RA-010 NORD lists the sixteen 5.1 values in nord order', () => {
    const rows = nordBlock().trim().split('\n').map((line) => line.trim());
    const expected = NORD_5_1.map((hex) => `Rgb::new(0x${hex.slice(1, 3)}, 0x${hex.slice(3, 5)}, 0x${hex.slice(5, 7)}),`);
    expect(rows).toEqual(expected);
  });

  test('TOK-001 generated.rs starts with the generated header', () => {
    expect(rust.startsWith('// generated by design/src — do not edit (TOK-001)\n')).toBe(true);
  });

  test('RA-010 terminal colours reference NORD by index', () => {
    expect(rust).toContain('pub const TERMINAL_BACKGROUND: Rgb = NORD[0];');
    expect(rust).toContain('pub const TERMINAL_FOREGROUND: Rgb = NORD[4];');
    expect(rust).toContain('NORD[1], NORD[11], NORD[14], NORD[13], NORD[9], NORD[15], NORD[8], NORD[5]');
  });

  test('RA-010 terminal tokens do not appear in CSS, TypeScript or the reference page', () => {
    for (const text of [css, typescript, reference]) {
      expect(text).not.toMatch(/ansi/i);
      expect(text).not.toContain('terminal');
    }
  });
});
